"""An annotation's pk becomes the ordinary integer id; its UUID stays as ``uuid``.

The shape's pk was a UUID, carried over from the ROI model it replaced, while every other
model's is a bigint. Django cannot alter a UUID pk into an auto field (there is no cast), so
the database side is written by hand and the state side is what ``makemigrations`` derives.

The ids are minted in drawing order (``created_at``, then the old UUID for a tie or a
shape with no time). A shape that only survives in history -- deleted since -- gets an id
after every live one, the same for all its history rows, so no history row ever shares an
id with a live shape it is not.

The five foreign keys are retyped IN PLACE (``ALTER COLUMN ... TYPE bigint USING``), never
dropped and re-added: dropping a column drops every constraint over it, and
``metric_target_is_one_object`` and the two unique constraints would vanish while the
migration state still says they exist. Irreversible: restore the dump taken before it.
"""

