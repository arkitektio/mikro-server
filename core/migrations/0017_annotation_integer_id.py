    """
    CREATE TABLE core_annotation_id_map (uuid uuid PRIMARY KEY, id bigint NOT NULL UNIQUE);
    INSERT INTO core_annotation_id_map (uuid, id)
        SELECT id, row_number() OVER (ORDER BY created_at NULLS FIRST, id) FROM core_annotation;
    INSERT INTO core_annotation_id_map (uuid, id)
        SELECT g.id,
               (SELECT coalesce(max(id), 0) FROM core_annotation_id_map)
               + row_number() OVER (ORDER BY g.first_seen, g.id)
        FROM (
            SELECT h.id, min(h.history_date) AS first_seen
            FROM core_historicalannotation h
            WHERE NOT EXISTS (SELECT 1 FROM core_annotation a WHERE a.id = h.id)
            GROUP BY h.id
        ) g;
    CREATE FUNCTION core_annotation_new_id(old uuid) RETURNS bigint
        LANGUAGE sql STABLE AS $$ SELECT id FROM core_annotation_id_map WHERE uuid = old $$;
    """,
    # The foreign keys go first, so the pk under them can be swapped.
    *(f"ALTER TABLE {table} DROP CONSTRAINT {fk};" for table, _, fk in TARGETS),
